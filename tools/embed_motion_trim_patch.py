#!/usr/bin/env python3
"""Embed the pinned TR01 profile without reading manufacturer firmware."""

import argparse
import hashlib
from pathlib import Path

import assemble_motion_trim as assembly
import build_motion_trim_patch as builder
import build_platform_patch as platform


def section_offsets():
    """Return application-relative offsets for every pinned TR01 section."""
    offsets = {name: item[0] for name, item in platform.HOOKS.items()}
    offsets.update({name: item[0] for name, item in assembly.TRIM_HOOKS.items()})
    offsets.update(
        candidate=platform.CODE_OFFSET,
        descriptor=platform.LAYOUT["descriptor_offset"],
    )
    return {name: offset - platform.APP_OFFSET for name, offset in offsets.items()}


def original_hooks():
    """Return the R7 instructions replaced by the cumulative TR01 payload."""
    return {
        **{name: item[1] for name, item in platform.HOOKS.items()},
        **{
            name: bytes.fromhex(assembly.HOOK_ORIGINALS[name])
            for name in assembly.TRIM_HOOKS
        },
    }


def render(llvm_bin=None):
    """Render reconstruction, preparation and exact FP01 removal helpers."""
    sections, _, _ = builder.compile_patch(llvm_bin)
    offsets = section_offsets()
    lines = [
        "#pragma once",
        "// Generated by tools/embed_motion_trim_patch.py from project-owned sections.",
        "// The caller must verify exact source, intermediate R7 and complete output hashes.",
        '#include "platform_patch.h"',
        "namespace esphome::desk_firmware_update {",
        f'static constexpr const char *TR01_SHA = "{builder.OUTPUT_APP_SHA256}";',
        f"static constexpr size_t TR01_PAYLOAD_SIZE = {builder.PAYLOAD_SIZE};",
    ]
    for name in builder.SECTION_ORDER:
        data = sections[name]
        lines += [
            f"// {name}: SHA-256 {hashlib.sha256(data).hexdigest()}",
            f"static constexpr uint8_t TR01_{name.upper()}[] = {{",
        ]
        for start in range(0, len(data), 16):
            lines.append(
                "  " + ",".join(f"0x{b:02x}" for b in data[start : start + 16]) + ","
            )
        lines.append("};")
    lines.append("inline uint8_t tr01_byte(size_t offset, uint8_t stock) {")
    for name in builder.SECTION_ORDER:
        offset, symbol = offsets[name], "TR01_" + name.upper()
        lines.append(
            f"  if (offset >= 0x{offset:x} && offset < 0x{offset:x} + sizeof({symbol})) return {symbol}[offset - 0x{offset:x}];"
        )
    lines += [
        "  return rs01_byte(offset, stock);",
        "}",
        "inline bool apply_motion_trim(uint8_t *image, size_t size) {",
        "  if (!image || size != IMAGE_SIZE) return false;",
    ]
    for name, data in original_hooks().items():
        values = ",".join(f"0x{b:02x}" for b in data)
        lines += [
            f"  const uint8_t before_{name}[] = {{{values}}};",
            f"  if (std::memcmp(image + 0x{offsets[name]:x}, before_{name}, sizeof(before_{name}))) return false;",
        ]
    lines.append(
        f"  for (size_t i = 0x{offsets['candidate']:x}; i < IMAGE_SIZE; ++i) if (image[i] != 255) return false;"
    )
    for name in builder.SECTION_ORDER:
        symbol = "TR01_" + name.upper()
        lines.append(
            f"  std::memcpy(image + 0x{offsets[name]:x}, {symbol}, sizeof({symbol}));"
        )
    lines += [
        "  return true;",
        "}",
        "// Restore R7 only after the caller has verified the complete FP01 hash.",
        "inline bool remove_platform_for_motion_trim(uint8_t *image, size_t size) {",
        "  if (!image || size != IMAGE_SIZE) return false;",
    ]
    for name in (*platform.HOOKS, "candidate", "descriptor"):
        symbol = "FP01_" + name.upper()
        lines.append(
            f"  if (std::memcmp(image + 0x{offsets[name]:x}, {symbol}, sizeof({symbol}))) return false;"
        )
    for name, (_, data) in platform.HOOKS.items():
        values = ",".join(f"0x{b:02x}" for b in data)
        lines += [
            f"  const uint8_t before_{name}[] = {{{values}}};",
            f"  std::memcpy(image + 0x{offsets[name]:x}, before_{name}, sizeof(before_{name}));",
        ]
    for name in ("candidate", "descriptor"):
        lines.append(
            f"  std::memset(image + 0x{offsets[name]:x}, 255, sizeof(FP01_{name.upper()}));"
        )
    lines += [
        "  return true;",
        "}",
        "}  // namespace esphome::desk_firmware_update",
        "",
    ]
    return "\n".join(lines)


def main():
    """Regenerate TR01 sections or reject stale checked-in output."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--llvm-bin", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = platform.ROOT / "components/desk_firmware_update/motion_trim_patch.h"
    expected = render(args.llvm_bin)
    if args.check:
        if not output.is_file() or output.read_text() != expected:
            raise SystemExit(
                "motion_trim_patch.h is stale: run tools/embed_motion_trim_patch.py"
            )
    else:
        output.write_text(expected)


if __name__ == "__main__":
    main()
