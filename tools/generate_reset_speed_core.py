#!/usr/bin/env python3
"""Generate reviewable RS01 assembly with pinned clang 23.1.0; no vendor input."""

import argparse
import hashlib
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "tools/patches/reset_speed.c"
OUTPUT = ROOT / "tools/patches/reset_speed_core.S"
PREFIX = "// reset_speed.c SHA-256: "


def check_source():
    """Reject assembly whose recorded C-source digest is missing or stale.

    This checks the source marker, not the complete compiler output.
    """
    expected = PREFIX + hashlib.sha256(SOURCE.read_bytes()).hexdigest()
    if not OUTPUT.is_file() or OUTPUT.read_text().splitlines()[1] != expected:
        raise ValueError("reset_speed_core.S is stale; regenerate with clang 23.1.0")


def generate(clang):
    """Return Cortex-M0 assembly and its source marker from the supplied clang.

    Require a version banner containing "clang version 23.1.0" and capture
    assembly output without writing the generated assembly file.
    """
    version = subprocess.run(
        [str(clang), "--version"], capture_output=True, text=True, check=True
    ).stdout.splitlines()[0]
    if "clang version 23.1.0" not in version:
        raise ValueError("RS01 C generation requires clang 23.1.0")
    command = [
        str(clang),
        "--target=arm-none-eabi",
        "-mcpu=cortex-m0",
        "-mthumb",
        "-Oz",
        "-ffreestanding",
        "-fno-builtin",
        "-fno-unwind-tables",
        "-fno-asynchronous-unwind-tables",
        "-Wall",
        "-Wextra",
        "-Werror",
        "-S",
        str(SOURCE),
        "-o",
        "-",
    ]
    assembly = subprocess.run(
        command, capture_output=True, text=True, check=True
    ).stdout
    return (
        "// Generated by tools/generate_reset_speed_core.py, clang 23.1.0.\n"
        + PREFIX
        + hashlib.sha256(SOURCE.read_bytes()).hexdigest()
        + "\n"
        + assembly
    )


def main():
    """Check the source marker, or compare or replace assembly using --clang.

    --check without --clang checks only the C-source digest marker. Generation
    requires a version banner containing "clang version 23.1.0".
    """
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--clang", type=Path)
    p.add_argument("--check", action="store_true")
    a = p.parse_args()
    if a.check and not a.clang:
        check_source()
        return
    if not a.clang:
        p.error("--clang requires the pinned clang 23.1.0 executable")
    result = generate(a.clang)
    if a.check:
        if OUTPUT.read_text() != result:
            p.error("reset_speed_core.S differs from pinned compiler output")
    else:
        OUTPUT.write_text(result)


if __name__ == "__main__":
    main()
