#!/usr/bin/env python3
"""Generate shared C/linker constants from the reviewed FP01 memory layout."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PATCHES = ROOT / "tools/patches"
# ABI 1 consumers retain their addresses. New allocations use only the former
# future reservation; they do not move the header, active modules or guard.
# RAM ABI alone does not identify enabled features; use the image identity.
ABI1_SLOTS = {
    "header": (0, 32),
    "buzzer": (32, 16),
    "display": (48, 16),
    "volume": (64, 16),
    "trim": (80, 16),
    "transaction": (96, 64),
    "abi_reserve": (160, 96),
    "guard": (1008, 16),
}


def load_layout(path=None):
    """Validate the FP01 flash and RAM allocation before consuming its values."""
    layout = json.loads((path or PATCHES / "platform_layout.json").read_text())
    if (
        layout["flash_base"] != 0x08000000
        or layout["full_size"] != 65536
        or layout["application_offset"] != 0x2800
        or layout["application_size"] != 55296
        or layout["loader_erase_size"] != 54272
        or layout["identifier"] != "FP01"
        or layout["descriptor_magic"] != "T150FP01"
        or layout["descriptor_size"] != 32
        or layout["code_offset"] != 0xA010
        or layout["code_end"] != layout["descriptor_offset"]
        or layout["descriptor_offset"] + 32 != layout["payload_end"]
        or layout["payload_end"] != 0xFC00
        or layout["application_offset"] + layout["payload_size"] != 0xFC00
        or layout["application_offset"] + layout["application_size"] != 0x10000
        or layout["ram_start"] != 0x20001000
        or layout["ram_size"] != 1024
        or layout["initial_msp"] != 0x20000FC8
        or layout["layout_version"] != 1
        or layout["ram_abi"] != 1
    ):
        raise ValueError("Unexpected FP01 layout")
    end = 0
    names = set()
    for slot in layout["slots"]:
        if (
            slot["name"] in names
            or slot["offset"] != end
            or slot["size"] <= 0
            or slot["offset"] % 4
            or slot["size"] % 4
        ):
            raise ValueError("Overlapping, unaligned or unnamed RAM allocation")
        position = (slot["offset"], slot["size"])
        if slot["name"] in ABI1_SLOTS and position != ABI1_SLOTS[slot["name"]]:
            raise ValueError("Existing RAM ABI allocation moved or resized")
        names.add(slot["name"])
        end += slot["size"]
    if end != layout["ram_size"] or names != {
        "header",
        "buzzer",
        "display",
        "volume",
        "trim",
        "transaction",
        "abi_reserve",
        "trim_owner",
        "trim_record",
        "trim_i2c",
        "trim_adapter",
        "future",
        "guard",
    }:
        raise ValueError("RAM allocation does not cover the reservation")
    if layout["slots"][-1] != dict(name="guard", offset=1008, size=16):
        raise ValueError("Upper guard moved")
    return layout


def generated(layout):
    """Return deterministic C and linker views of the same memory reservation."""
    constants = {
        "LAYOUT_VERSION": layout["layout_version"],
        "RAM_ABI": layout["ram_abi"],
        "CODE_START": layout["flash_base"] + layout["code_offset"],
        "CODE_END": layout["flash_base"] + layout["code_end"],
        "DESCRIPTOR_ADDRESS": layout["flash_base"] + layout["descriptor_offset"],
        "PAYLOAD_SIZE": layout["payload_size"],
        "LOADER_ERASE_SIZE": layout["loader_erase_size"],
        "APPLICATION_SIZE": layout["application_size"],
        "RAM_START": layout["ram_start"],
        "RAM_SIZE": layout["ram_size"],
        "RAM_END": layout["ram_start"] + layout["ram_size"],
        "INITIAL_MSP": layout["initial_msp"],
    }
    for slot in layout["slots"]:
        constants[slot["name"].upper() + "_ADDRESS"] = (
            layout["ram_start"] + slot["offset"]
        )
        constants[slot["name"].upper() + "_SIZE"] = slot["size"]
    header = "/* Generated by tools/generate_platform_layout.py. */\n"
    header += "#ifndef DESK_PLATFORM_LAYOUT_H\n#define DESK_PLATFORM_LAYOUT_H\n"
    header += "".join(
        f"#define PLATFORM_{name} 0x{value:x}u\n" for name, value in constants.items()
    )
    header += "#endif\n"
    linker = "/* Generated by tools/generate_platform_layout.py. */\n"
    linker += "".join(
        f"PLATFORM_{name} = 0x{value:x};\n" for name, value in constants.items()
    )
    linker += 'ASSERT(PLATFORM_RAM_END <= 0x20002000, "C8 SRAM overflow")\n'
    linker += 'ASSERT(PLATFORM_INITIAL_MSP == 0x20000fc8, "native MSP changed")\n'
    return {"platform_layout.h": header, "platform_layout.ld": linker}


def check_source():
    """Reject stale generated views so builders never use a second layout."""
    for name, contents in generated(load_layout()).items():
        if (PATCHES / name).read_text() != contents:
            raise ValueError(f"{name} is stale; regenerate the platform layout")


def main():
    """Write generated layout views, or verify them without changing files."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        check_source()
    else:
        for name, contents in generated(load_layout()).items():
            (PATCHES / name).write_text(contents)


if __name__ == "__main__":
    main()
