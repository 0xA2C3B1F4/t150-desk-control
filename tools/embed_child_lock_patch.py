#!/usr/bin/env python3
"""Embed only the reviewed CL01 replacement assembly, without a vendor image.

The existing builder supplies the linker layout and pinned application hash.
LLVM temporary files stay under TMPDIR and are removed by that builder.
"""
import argparse
import hashlib
from pathlib import Path

from build_child_lock_patch import APP_OFFSET, OUTPUT_APP_SHA256, ROOT, SECTIONS, compile_patch


def render(llvm_bin=None):
    sections, _ = compile_patch(llvm_bin)
    lines = ["#pragma once", "// Generated by tools/embed_child_lock_patch.py from our replacement assembly.",
             "// Application offsets. No original controller image is embedded.",
             '#include "dt02_patch.h"', "namespace esphome::desk_firmware_update {",
             f'static constexpr const char *CL01_SHA = "{OUTPUT_APP_SHA256}";']
    for name, data in sections.items():
        lines += [f"// {name}: SHA-256 {hashlib.sha256(data).hexdigest()}",
                  f"static constexpr uint8_t CL01_{name.upper()}[] = {{"]
        for offset in range(0, len(data), 16):
            lines.append("  " + ",".join(f"0x{b:02x}" for b in data[offset:offset+16]) + ",")
        lines.append("};")
    lines += ["// Reconstruct a CL01 block from the exact original during recovery.",
              "inline uint8_t cl01_byte(size_t offset, uint8_t stock) {"]
    for name in sections:
        offset = SECTIONS[name][0] - APP_OFFSET
        symbol = "CL01_" + name.upper()
        lines.append(f"  if (offset>=0x{offset:x} && offset<0x{offset:x} + sizeof({symbol})) return {symbol}[offset-0x{offset:x}];")
    lines += ["  return dt02_byte(offset,stock);", "}",
              "// The caller must verify the complete DT02 input and CL01 output hashes.",
              "inline bool apply_child_lock(uint8_t *image, size_t size) {",
              "  const uint8_t gpio[]={0x02,0x46,0x12,0x8a,0x00,0x20,0x0a,0x42};",
              "  const uint8_t boot[]={0xff,0xf7,0x12,0xf8}, hook[]={0x00,0xf0,0x2d,0xfe};",
              "  if (!image || size!=IMAGE_SIZE || std::memcmp(image+0x1b88,gpio,sizeof(gpio)) ||",
              "      std::memcmp(image+0x5df8,boot,sizeof(boot)) || std::memcmp(image+0x53ae,hook,sizeof(hook)) ||",
              "      std::memcmp(image+0x600c,DT02_CODE,sizeof(DT02_CODE))) return false;",
              "  for (size_t i=0; i<2048; ++i) if (image[0x6400+i]!=255) return false;"]
    for name in sections:
        offset = SECTIONS[name][0] - APP_OFFSET
        symbol = "CL01_" + name.upper()
        lines.append(f"  std::memcpy(image+0x{offset:x},{symbol},sizeof({symbol}));")
    lines += ["  return true;", "}", "}  // namespace esphome::desk_firmware_update", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--llvm-bin", type=Path)
    args = parser.parse_args()
    expected = render(args.llvm_bin)
    output = ROOT / "components/desk_firmware_update/child_lock_patch.h"
    if args.check:
        if output.read_text() != expected:
            raise SystemExit("child_lock_patch.h is stale: run tools/embed_child_lock_patch.py")
    else:
        output.write_text(expected)


if __name__ == "__main__":
    main()
