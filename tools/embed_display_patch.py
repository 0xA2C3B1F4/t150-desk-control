#!/usr/bin/env python3
"""Embed the current display timeout firmware using only project-owned sections."""

import argparse
from pathlib import Path

import build_buzzer_patch as buzzer
import build_display_patch as builder
import embed_motion_trim_patch as previous


def render(llvm_bin=None):
    """Render byte reconstruction, current preparation and exact BZ01 removal."""
    sections, _, _ = builder.compile_patch(llvm_bin)
    offsets = previous.section_offsets()
    originals = previous.original_hooks()
    for name, (offset, data) in builder.HOOKS.items():
        offsets[name] = offset - builder.platform.APP_OFFSET
        originals[name] = data
    buzzer_originals = previous.original_hooks()
    buzzer_originals.update({name: data for name, (_, data) in buzzer.HOOKS.items()})
    lines = [
        "#pragma once",
        "// Generated by tools/embed_display_patch.py from project-owned sections.",
        '#include "buzzer_patch.h"',
        "namespace esphome::desk_firmware_update {",
        f'static constexpr const char *DS01_SHA = "{builder.OUTPUT_APP_SHA256}";',
        f"static constexpr size_t DS01_PAYLOAD_SIZE = {builder.PAYLOAD_SIZE};",
    ]
    for name in builder.SECTION_ORDER:
        lines.append(f"static constexpr uint8_t DS01_{name.upper()}[] = {{")
        data = sections[name]
        for start in range(0, len(data), 16):
            lines.append(
                "  "
                + ",".join(f"0x{byte:02x}" for byte in data[start : start + 16])
                + ","
            )
        lines.append("};")
    lines.append("inline uint8_t ds01_byte(size_t offset, uint8_t stock) {")
    for name in builder.SECTION_ORDER:
        offset, symbol = offsets[name], "DS01_" + name.upper()
        lines.append(
            f"  if (offset >= 0x{offset:x} && offset < 0x{offset:x} + sizeof({symbol})) return {symbol}[offset - 0x{offset:x}];"
        )
    lines += [
        "  return rs01_byte(offset, stock);",
        "}",
        "inline bool apply_display_timeout(uint8_t *image, size_t size) {",
        "  if (!image || size != IMAGE_SIZE) return false;",
    ]
    for name, data in originals.items():
        values = ",".join(f"0x{byte:02x}" for byte in data)
        lines += [
            f"  const uint8_t before_{name}[] = {{{values}}};",
            f"  if (std::memcmp(image + 0x{offsets[name]:x}, before_{name}, sizeof(before_{name}))) return false;",
        ]
    lines.append(
        f"  for (size_t i = 0x{offsets['candidate']:x}; i < IMAGE_SIZE; ++i) if (image[i] != 255) return false;"
    )
    for name in builder.SECTION_ORDER:
        symbol = "DS01_" + name.upper()
        lines.append(
            f"  std::memcpy(image + 0x{offsets[name]:x}, {symbol}, sizeof({symbol}));"
        )
    lines += [
        "  return true;",
        "}",
        "// The caller verifies the full BZ01 hash before removal and the R7 hash after it.",
        "inline bool remove_buzzer_profiles(uint8_t *image, size_t size) {",
        "  if (!image || size != IMAGE_SIZE) return false;",
    ]
    for name in buzzer.SECTION_ORDER:
        symbol = "BZ01_" + name.upper()
        lines.append(
            f"  if (std::memcmp(image + 0x{offsets[name]:x}, {symbol}, sizeof({symbol}))) return false;"
        )
    for name, data in buzzer_originals.items():
        values = ",".join(f"0x{byte:02x}" for byte in data)
        lines += [
            f"  const uint8_t before_{name}[] = {{{values}}};",
            f"  std::memcpy(image + 0x{offsets[name]:x}, before_{name}, sizeof(before_{name}));",
        ]
    for name in ("candidate", "descriptor"):
        lines.append(
            f"  std::memset(image + 0x{offsets[name]:x}, 255, sizeof(BZ01_{name.upper()}));"
        )
    lines += [
        "  return true;",
        "}",
        "}  // namespace esphome::desk_firmware_update",
        "",
    ]
    return "\n".join(lines)


def main():
    """Generate the current payload header or check its exact compiler output."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--llvm-bin", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = builder.platform.ROOT / "components/desk_firmware_update/display_patch.h"
    expected = render(args.llvm_bin)
    if args.check:
        if not output.is_file() or output.read_text() != expected:
            raise SystemExit(
                "display_patch.h is stale: run tools/embed_display_patch.py"
            )
    else:
        output.write_text(expected)


if __name__ == "__main__":
    main()
