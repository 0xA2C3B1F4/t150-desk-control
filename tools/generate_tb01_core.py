#!/usr/bin/env python3
"""Generate TB01 Cortex-M0 assembly with pinned clang 23.1.0, without firmware."""

import argparse
import hashlib
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
PATCHES = ROOT / "tools/patches"
SOURCES = {
    "tb01_core.c": "tb01_core.S",
    "tb01.c": "tb01_platform.S",
}
HEADER = "tb01_core.h"


def _markers(source):
    return [
        f"// {name} SHA-256: {hashlib.sha256((PATCHES / name).read_bytes()).hexdigest()}"
        for name in (source, HEADER)
    ]


def check_source():
    """Reject missing assembly or stale C-source and shared-header digest markers."""
    for source, output in SOURCES.items():
        path = PATCHES / output
        if not path.is_file() or path.read_text().splitlines()[1:3] != _markers(source):
            raise ValueError(f"{output} is stale; regenerate with clang 23.1.0")


def generate(clang):
    """Compile both TB01 C sources to assembly with exactly clang 23.1.0."""
    version = subprocess.run(
        [str(clang), "--version"], capture_output=True, text=True, check=True
    ).stdout.splitlines()
    if not version or not re.search(r"\bclang version 23\.1\.0(?:\s|$)", version[0]):
        raise ValueError("TB01 C generation requires clang 23.1.0")
    outputs = {}
    for source, output in SOURCES.items():
        command = [
            str(clang),
            "--target=arm-none-eabi",
            "-mcpu=cortex-m0",
            "-mthumb",
            "-std=c11",
            "-Oz",
            "-ffreestanding",
            "-fno-builtin",
            "-fno-unwind-tables",
            "-fno-asynchronous-unwind-tables",
            "-Wall",
            "-Wextra",
            "-Werror",
            "-S",
            str(PATCHES / source),
            "-o",
            "-",
        ]
        assembly = subprocess.run(
            command, capture_output=True, text=True, check=True
        ).stdout
        outputs[output] = (
            "// Generated by tools/generate_tb01_core.py, clang 23.1.0.\n"
            + "\n".join(_markers(source))
            + "\n"
            + assembly
        )
    return outputs


def _normalize_identity(assembly):
    lines = assembly.splitlines(keepends=True)
    identities = []
    pattern = re.compile(r'([ \t]*\.ident[ \t]+)"[^"\\\r\n]*"([ \t]*)(\r?\n|$)')
    for index, line in enumerate(lines):
        if match := pattern.fullmatch(line):
            identities.append(index)
            lines[index] = match[1] + '"<compiler identity>"' + match[2] + match[3]
        elif re.match(r"[ \t]*\.ident\b", line):
            raise ValueError("Malformed compiler identification directive")
    if len(identities) != 1:
        raise ValueError("Expected exactly one compiler identification directive")
    return "".join(lines)


def check_assembly(expected, generated):
    """Require equal compiler output except for the discarded .ident string."""
    if _normalize_identity(expected) != _normalize_identity(generated):
        raise ValueError("TB01 assembly differs from pinned compiler output")


def main():
    """Check source markers, or regenerate or compare assembly with pinned clang."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--clang", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        if args.check and not args.clang:
            check_source()
            return
        if not args.clang:
            parser.error("--clang requires the pinned clang 23.1.0 executable")
        for name, assembly in generate(args.clang).items():
            path = PATCHES / name
            if args.check:
                check_assembly(path.read_text(), assembly)
            else:
                path.write_text(assembly)
    except (OSError, ValueError, subprocess.SubprocessError) as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
