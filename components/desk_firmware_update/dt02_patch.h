// Derive a target block from a hash-validated stock image without allocating
// another whole image. Also used to validate a torn DT02 write during recovery.
inline uint8_t dt02_byte(size_t offset, uint8_t stock) {
  const uint8_t sleep_patch[]={0x1b,0x18,0x0a,0xe0}, hook_patch[]={0x00,0xf0,0x2d,0xfe};
  if(offset>=0x1656 && offset<0x165a) return sleep_patch[offset-0x1656];
  if(offset>=0x53ae && offset<0x53b2) return hook_patch[offset-0x53ae];
  if(offset>=0x600c && offset<0x600c+sizeof(DT02_CODE)) return DT02_CODE[offset-0x600c];
  return stock;
}
inline bool apply_dt02(uint8_t *image, size_t size) {
  const uint8_t sleep[] = {0x18,0x18,0x3c,0x28}, hook[] = {0xca,0x48,0x02,0x68};
  if (!image || size != IMAGE_SIZE || std::memcmp(image+0x1656,sleep,4) ||
      std::memcmp(image+0x53ae,hook,4)) return false;
  for (size_t i=0; i<sizeof(DT02_CODE); ++i) if (image[0x600c+i]!=255) return false;
  const uint8_t sleep_patch[] = {0x1b,0x18,0x0a,0xe0}, hook_patch[] = {0x00,0xf0,0x2d,0xfe};
  std::memcpy(image+0x1656,sleep_patch,4);
  std::memcpy(image+0x53ae,hook_patch,4);
  std::memcpy(image+0x600c,DT02_CODE,sizeof(DT02_CODE));
  return true;
}
